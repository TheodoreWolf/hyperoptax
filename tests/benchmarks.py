"""Reusable optimizer benchmarks.

Codifies the convergence experiments from ``notebooks/high_dimensional.ipynb``
and ``notebooks/performance.ipynb`` into a harness that runs against *any*
``Optimizer`` subclass through the shared ``init`` / ``optimize_scan`` API.

Objectives are standard nD test functions (global min 0). We maximise ``-fn``,
so the true optimum of the maximisation target is 0 and

    regret = 0 - running_best_score  >= 0

Run ``python tests/benchmarks.py`` to regenerate ``BENCHMARKS.md``.
"""

import dataclasses
import inspect
import time
from pathlib import Path
from typing import Callable

import jax
import jax.numpy as jnp
import numpy as np

from hyperoptax.bayesian import BayesianSearch
from hyperoptax.random import RandomSearch
from hyperoptax.spaces import LinearSpace, Space
from hyperoptax.tpe import TPESearch

# ── Objective functions: (D,) array -> scalar, global min 0 ──────────────────


def sphere(x):
    """Convex bowl. Min 0 at 0. Domain [-5, 5]^D."""
    return jnp.sum(x**2)


def ackley(x):
    """Multimodal, near-flat tails. Min 0 at 0. Domain [-5, 5]^D."""
    return (
        -20.0 * jnp.exp(-0.2 * jnp.sqrt(jnp.mean(x**2)))
        - jnp.exp(jnp.mean(jnp.cos(2 * jnp.pi * x)))
        + jnp.e
        + 20.0
    )


def rosenbrock(x):
    """Curved valley. Min 0 at 1. Domain [-2, 2]^D."""
    return jnp.sum(100.0 * (x[1:] - x[:-1] ** 2) ** 2 + (1.0 - x[:-1]) ** 2)


@dataclasses.dataclass(frozen=True)
class Benchmark:
    name: str
    fn: Callable
    space_template: Space
    dim: int
    true_opt: float = 0.0

    @property
    def space(self) -> dict:
        return {f"x{i}": self.space_template for i in range(self.dim)}

    @property
    def wrapper(self) -> Callable:
        """JAX-traceable (key, config) -> scalar; maximises -fn."""
        keys = [f"x{i}" for i in range(self.dim)]
        fn = self.fn

        def w(key, config):
            return -fn(jnp.stack([config[k] for k in keys]))

        return w


BENCHMARKS = {
    "sphere_2d": Benchmark("sphere_2d", sphere, LinearSpace(-5.0, 5.0), 2),
    "ackley_5d": Benchmark("ackley_5d", ackley, LinearSpace(-5.0, 5.0), 5),
    "rosenbrock_5d": Benchmark("rosenbrock_5d", rosenbrock, LinearSpace(-2.0, 2.0), 5),
}

# Optimizers to benchmark: name -> (class, extra init kwargs).
# Add a new Optimizer subclass here and every benchmark/test picks it up.
OPTIMIZERS = {
    "random": (RandomSearch, {}),
    "bayesian": (BayesianSearch, {}),
    "tpe": (TPESearch, {"n_warmup": 5}),
}


def run(
    opt_cls, benchmark: Benchmark, *, n_budget=50, n_seeds=3, seed=0, **init_kwargs
):
    """Run ``opt_cls`` on ``benchmark`` across seeds (vmapped, jitted).

    Forces ``n_parallel=1`` so every optimizer evaluates exactly ``n_budget``
    points and regret curves are directly comparable per evaluation. Passes
    ``n_max`` only to optimizers whose ``init`` accepts it.

    Returns ``(regret, run_sec)`` where ``regret`` is ``(n_seeds, n_budget)``.
    """
    kwargs = {"n_parallel": 1, **init_kwargs}
    if "n_max" in inspect.signature(opt_cls.init).parameters:
        kwargs["n_max"] = n_budget
    state0, opt = opt_cls.init(benchmark.space, **kwargs)
    wrapper = benchmark.wrapper
    keys = jax.random.split(jax.random.PRNGKey(seed), n_seeds)

    def one(key):
        _, (_, res) = opt.optimize_scan(state0, key, wrapper, n_budget)
        return res.reshape(-1)  # (n_budget,)

    run_fn = jax.jit(jax.vmap(one))
    run_fn(keys).block_until_ready()  # compile
    t0 = time.perf_counter()
    raw = np.array(run_fn(keys).block_until_ready())  # (n_seeds, n_budget)
    run_sec = time.perf_counter() - t0

    regret = benchmark.true_opt - np.maximum.accumulate(raw, axis=1)
    return regret, run_sec


def _report() -> str:
    """Run the full suite and render a Markdown report."""
    n_budget, n_seeds = 50, 3
    rows = {}  # opt_name -> {bench_name: (median_final_regret, run_sec)}
    for opt_name, (cls, extra) in OPTIMIZERS.items():
        rows[opt_name] = {}
        for bname, bench in BENCHMARKS.items():
            regret, run_sec = run(
                cls, bench, n_budget=n_budget, n_seeds=n_seeds, **extra
            )
            rows[opt_name][bname] = (float(np.median(regret[:, -1])), run_sec)
            print(
                f"  {opt_name:9s} {bname:14s} "
                f"regret={rows[opt_name][bname][0]:.4g}  {run_sec * 1e3:.0f}ms"
            )

    bnames = list(BENCHMARKS)
    lines = [
        "# Optimizer Benchmarks",
        "",
        f"Median final regret over {n_seeds} seeds after {n_budget} evaluations "
        "(lower is better). Regret = optimum − running best; global optimum is 0. "
        "All runs use `n_parallel=1`. Generated by `python tests/benchmarks.py`.",
        "",
        "## Final regret",
        "",
        "| Optimizer | " + " | ".join(bnames) + " |",
        "|" + "---|" * (len(bnames) + 1),
    ]
    for opt_name in OPTIMIZERS:
        cells = [f"{rows[opt_name][b][0]:.4g}" for b in bnames]
        lines.append(f"| {opt_name} | " + " | ".join(cells) + " |")

    lines += [
        "",
        "## Wall time (vmapped over seeds, compiled)",
        "",
        "| Optimizer | " + " | ".join(bnames) + " |",
        "|" + "---|" * (len(bnames) + 1),
    ]
    for opt_name in OPTIMIZERS:
        cells = [f"{rows[opt_name][b][1] * 1e3:.2f} ms" for b in bnames]
        lines.append(f"| {opt_name} | " + " | ".join(cells) + " |")
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    print("Running benchmark suite...")
    md = _report()
    out = Path(__file__).resolve().parent.parent / "BENCHMARKS.md"
    out.write_text(md)
    print(f"\nWrote {out}")
